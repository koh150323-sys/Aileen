// Deterministic pseudo-random generator with seed
function createSeededRandom(seed: number) {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

// Generate OHLCV series for given timeframe and baseline price
function generateHistory(basePrice: number, seed: number): MarketAsset['history'] {
  const rand = createSeededRandom(seed);
  
  const generateSeries = (count: number, volatility: number, trend: number): OHLCV[] => {
    const list: OHLCV[] = [];
    let curr = basePrice * (1 - trend * 0.5);
    const now = Date.now();
    const intervalMs = (86400000 * 30) / count;

    for (let i = 0; i < count; i++) {
      const deltaPercent = (rand() - 0.48) * volatility + (trend / count);
      const open = curr;
      const change = curr * deltaPercent;
      const close = Math.max(open + change, open * 0.1);
      const high = Math.max(open, close) + rand() * volatility * curr * 0.5;
      const low = Math.min(open, close) - rand() * volatility * curr * 0.5;
      const volume = Math.floor(basePrice * 10000 * (0.8 + rand() * 0.6));
      
      const ts = now - (count - 1 - i) * intervalMs;
      const d = new Date(ts);
      const timeStr = count <= 24 
        ? `${d.getHours().toString().padStart(2, '0')}:${d.getMinutes().toString().padStart(2, '0')}`
        : `${d.getMonth() + 1}/${d.getDate()}`;

      list.push({
        time: timeStr,
        timestamp: ts,
        open: Number(open.toFixed(2)),
        high: Number(high.toFixed(2)),
        low: Number(Math.max(low, 0.01).toFixed(2)),
        close: Number(close.toFixed(2)),
        volume,
      });

      curr = close;
    }
    return list;
  };

  return {
    '1D': generateSeries(24, 0.008, 0.004),
    '5D': generateSeries(30, 0.015, 0.012),
    '1M': generateSeries(30, 0.025, 0.03),
    '6M': generateSeries(40, 0.035, 0.08),
    '1Y': generateSeries(50, 0.04, 0.15),
    'ALL': generateSeries(60, 0.05, 0.35),
  };
}

function generateSparkline(history1D: OHLCV[]): number[] {
  return history1D.map(h => h.close);
}

